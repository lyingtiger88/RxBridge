/// Conservative mapping between dosage forms and administration routes.
/// This is a demo rule set, not a verified medicine database.
class MedicationFormRoute {
  static const forms = <String>[
    'قرص', 'قرص جویدنی', 'قرص زیرزبانی', 'کپسول', 'شربت', 'سوسپانسیون خوراکی',
    'آمپول / ویال', 'شیاف مقعدی', 'فرآورده واژینال', 'قطره', 'پماد', 'کرم',
    'اسپری', 'سایر'
  ];

  static const allRoutes = <String>[
    'خوراکی', 'خوراکی - جویدنی', 'زیرزبانی', 'تزریقی (نوع مشخص نشده)',
    'عضلانی', 'وریدی', 'زیرجلدی', 'داخل‌جلدی', 'مقعدی', 'واژینال',
    'چشمی', 'گوشی', 'داخل بینی', 'استنشاقی', 'موضعی', 'نیازمند تعیین مسیر', 'سایر'
  ];

  static const Map<String, String> _defaults = {
    'قرص': 'خوراکی',
    'قرص جویدنی': 'خوراکی - جویدنی',
    'قرص زیرزبانی': 'زیرزبانی',
    'کپسول': 'خوراکی',
    'شربت': 'خوراکی',
    'سوسپانسیون خوراکی': 'خوراکی',
    'آمپول / ویال': 'تزریقی (نوع مشخص نشده)',
    'شیاف مقعدی': 'مقعدی',
    'فرآورده واژینال': 'واژینال',
    'قطره': 'نیازمند تعیین مسیر',
    'پماد': 'موضعی',
    'کرم': 'موضعی',
    'اسپری': 'نیازمند تعیین مسیر',
    'سایر': 'سایر',
  };

  static String defaultRouteFor(String form) => _defaults[form] ?? 'نیازمند تعیین مسیر';

  static List<String> routesFor(String form) => switch (form) {
    'قرص' || 'کپسول' || 'شربت' || 'سوسپانسیون خوراکی' => const ['خوراکی'],
    'قرص جویدنی' => const ['خوراکی - جویدنی'],
    'قرص زیرزبانی' => const ['زیرزبانی'],
    'آمپول / ویال' => const ['تزریقی (نوع مشخص نشده)', 'عضلانی', 'وریدی', 'زیرجلدی', 'داخل‌جلدی'],
    'شیاف مقعدی' => const ['مقعدی'],
    'فرآورده واژینال' => const ['واژینال'],
    'قطره' => const ['نیازمند تعیین مسیر', 'چشمی', 'گوشی', 'داخل بینی', 'خوراکی'],
    'پماد' || 'کرم' => const ['موضعی', 'چشمی', 'گوشی', 'واژینال', 'مقعدی'],
    'اسپری' => const ['نیازمند تعیین مسیر', 'داخل بینی', 'استنشاقی', 'موضعی'],
    _ => const ['سایر', 'نیازمند تعیین مسیر'],
  };

  static bool isRouteAllowed(String form, String route) => routesFor(form).contains(route);

  static bool requiresSpecificRoute(String form, String route) =>
      (form == 'آمپول / ویال' && route == 'تزریقی (نوع مشخص نشده)') ||
      ((form == 'قطره' || form == 'اسپری') && route == 'نیازمند تعیین مسیر');

  static String helpTextFor(String form) => switch (form) {
    'آمپول / ویال' => 'پیش‌فرض فقط «تزریقی» است؛ مسیر دقیق باید از اطلاعات همان فرآورده تأیید شود.',
    'قطره' => 'قطره می‌تواند چشمی، گوشی، بینی یا خوراکی باشد؛ محل مصرف را مشخص کنید.',
    'اسپری' => 'اسپری می‌تواند بینی، استنشاقی یا موضعی باشد؛ مسیر را مشخص کنید.',
    'پماد' || 'کرم' => 'مسیر معمول موضعی است؛ فرآورده‌های چشمی، گوشی، واژینال یا مقعدی باید مشخص شوند.',
    _ => 'این نگاشت تقریبی است و باید با اطلاعات معتبر همان فرآورده تطبیق داده شود.',
  };
}
